type Key = keyof typeof it;
export type I18nKey = Key;

export function translate(_hass: HomeAssistant | undefined, key: Key, vars: Record<string, string | number> = {}): string {
  let s: string = it[key] ?? key;
  for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function formatNumber(_hass: HomeAssistant | undefined, value: number, digits = 2): string {
  return value.toLocaleString(_hass?.language ?? "it-IT", { maximumFractionDigits: digits });
}
